"""Write switch/blast-radius.template.yaml from the room and role instructions in switch/.

The .md files are the source; rerun this after editing them (make template).
"""

from pathlib import Path

SWITCH = Path(__file__).resolve().parent.parent / "switch"


def block(name: str, indent: int) -> str:
    text = (SWITCH / name).read_text().strip()
    pad = " " * indent
    return "|\n" + "\n".join(pad + line if line else "" for line in text.splitlines())


AGENT = """\
  {key}:
    type: agent
    name: {name}
    display_name: {display}
    description: "{description}"
    provider: {provider}
    machine: "{{machine}}"
    directory: "{{$agents_dir}}/{name}"
    repo: "https://github.com/{{gh_user}}/{repo}"
    auto_approve: true
    connections: [atlassian]
    addressing: {addressing}
    instructions: |
      You are {display}. Your working directory is a clone of {{gh_user}}/{repo}.
      Follow the instructions of the role you hold and of the room you are addressed in.
"""

ROOM = """\
  {key}:
    type: room
    group: blast_radius
    name: {name}
    description: "{description}"
    agents: [{agents}]
    users: ["{{$creator}}", "{{teammate}}"]
    aliases: {{{aliases}}}
    instructions: {instructions}
"""

# Switch reads a list item with a `value` key as an {if, value} conditional, and
# every reference has a `value`, so the references sit inside one `- value:` entry.
REPO_REF = """\
          - type: github
            name: {repo}
            description: "{description}"
            instructions: Use gh and git. Run make test with UPSTREAM_REF set to the upstream branch under review.
            value: {{urls: ["https://github.com/{{gh_user}}/{repo}"]}}
"""

agents = [
    ("coordinator", "br-coordinator", "Impact coordinator", "Coordinates the blast radius of one upstream change", "claude", "br-events-producer", "owner-agents"),
    ("dbt", "br-dbt", "dbt bot", "Speaks for br-analytics-dbt (owner: teammate)", "claude", "br-analytics-dbt", "{anyone_in: [schema_changes, analytics]}"),
    ("ml", "br-ml", "ML bot", "Speaks for br-ml-features (owner: teammate)", "codex", "br-ml-features", "{anyone_in: [schema_changes, ml_features]}"),
    ("dash", "br-dash", "Dashboards bot", "Speaks for br-dashboards-sql (owner: you)", "opencode", "br-dashboards-sql", "owner-agents"),
]

team_rooms = [
    ("analytics", "analytics", "Team room for br-analytics-dbt", "dbt", "dbt-bot", "br-analytics-dbt"),
    ("ml_features", "ml-features", "Team room for br-ml-features", "ml", "ml-bot", "br-ml-features"),
    ("dashboards", "dashboards", "Team room for br-dashboards-sql", "dash", "dash-bot", "br-dashboards-sql"),
]

out = ["""\
# Blast Radius: four agents, four rooms, one group with "depends on" links.
# Generated by scripts/build_template.py from switch/rooms and switch/roles.
# Load it in Switch Console: Templates, Import template. Before running, publish
# the demo repos (make seed) so each agent can clone its repo.
version: 2

params:
  gh_user:
    type: string
    description: GitHub owner of the four demo repos
    default: ayushgawai
  teammate:
    type: string
    description: Your teammate's username on the messaging app (owns the dbt and ML repos)
  machine:
    type: machine
    description: The machine the agents run on
    default: [$first]
    input: advanced

resources:
  blast_radius:
    type: group
    name: blast-radius
    description: Schema changes and the team rooms that depend on them
    links:
      - {from: schema_changes, to: analytics, label: depends on}
      - {from: schema_changes, to: ml_features, label: depends on}
      - {from: schema_changes, to: dashboards, label: depends on}
"""]

for key, name, display, description, provider, repo, addressing in agents:
    out.append(AGENT.format(key=key, name=name, display=display, description=description, provider=provider, repo=repo, addressing=addressing))

out.append(f"""\
  schema_changes:
    type: room
    group: blast_radius
    name: schema-changes
    description: Upstream schema and API changes, reviewed by every team that depends on them
    agents: [coordinator, dbt, ml, dash]
    users: ["{{$creator}}", "{{teammate}}"]
    aliases: {{coordinator: coordinator, dbt: dbt-bot, ml: ml-bot, dash: dash-bot}}
    instructions: {block("rooms/schema-changes.md", 6)}
    roles:
      - name: impact-coordinator
        exclusive: true
        instructions: {block("roles/impact-coordinator.md", 10)}
      - name: impact-checker
        exclusive: false
        instructions: {block("roles/impact-checker.md", 10)}
    references:
      - value:
""")
out.append(REPO_REF.format(repo="br-events-producer", description="The upstream repo whose changes this room reviews"))
out.append("""\
          - type: jira
            name: Jira BR
            description: Tickets for every breakage, assigned to the repo owner
            instructions: Use the Atlassian connection. Project key BR.
            value: {urls: ["https://ayushsunilgawai.atlassian.net/browse/BR"]}
    kickoff: |
      @coordinator assume the impact-coordinator role. @dbt-bot @ml-bot @dash-bot assume the impact-checker role. Then each say in one line which repo you speak for.
""")
for key, name, description, agent, alias, repo in team_rooms:
    out.append(ROOM.format(key=key, name=name, description=description, agents=agent, aliases=f"{agent}: {alias}", instructions=block(f"rooms/{name}.md", 6)))
    out.append("    references:\n      - value:\n" + REPO_REF.format(repo=repo, description=description))

(SWITCH / "blast-radius.template.yaml").write_text("".join(out))
print(SWITCH / "blast-radius.template.yaml")
